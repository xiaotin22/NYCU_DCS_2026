`protect

`define CYCLE_TIME 8.0
`define PATTERN_NUMBER 5000
`define SEED 23

module PATTERN (
    // output signals
    output reg        clk,
    output reg        rst_n,
    output reg        in_valid,
    output reg [7:0]  in_data,

    // input signals
    input             out_valid,
    input             out_data
);

// ========================================
// clock
// ========================================
real CYCLE = `CYCLE_TIME;
always #(CYCLE/2.0) clk = ~clk;
initial clk = 0;

// ========================================
// parameter & integer
// ========================================
parameter IMAGE_SIZE  = 8;
parameter NUM_PIXELS  = IMAGE_SIZE * IMAGE_SIZE;
parameter OUTPUT_SIZE = 6;
parameter NUM_OUTPUT  = OUTPUT_SIZE * OUTPUT_SIZE;
parameter THRESHOLD   = 128;
parameter STALL_PROB  = 10;
parameter STALL_CYCLE = 8; 
parameter OUTPUT_IDLE_TIMEOUT = 200;

integer   PATTERN_NUM = `PATTERN_NUMBER;

integer i, j, r, c;
integer seed = `SEED;
integer pattern_count, wait_count;
integer total_latency, pattern_latency;
integer rand_val;
integer out_bit_count;
integer fp;
integer idle_count;
integer current_cycle;
integer received_in_count; 

// ========================================
// wire & reg
// ========================================
reg [7:0]  image     [0:IMAGE_SIZE-1][0:IMAGE_SIZE-1];
reg        golden    [0:OUTPUT_SIZE-1][0:OUTPUT_SIZE-1];
reg input_done;
reg golden_flat [0:NUM_OUTPUT-1];

// Sobel kernel computation (signed arithmetic)
integer Gx, Gy, mag;
integer p00, p01, p02;
integer p10, p11, p12;
integer p20, p21, p22;

//================================================================
// initial
//================================================================
initial begin
    total_latency = 0;
    reset_task;

    for (pattern_count=0; pattern_count<PATTERN_NUM; pattern_count=pattern_count + 1) begin
        generate_image_task;
        compute_golden_task;
        flatten_golden_task;
        dump_debug_task;
        
        fork
            pattern_input_task;
            check_ans_task;
        join
    end

    YOU_PASS_task;
    #(CYCLE); $finish;
end

always @(*) begin
    if (in_valid === 1'b1 && out_valid === 1'b1) begin
        fail_task;
        $display("-----------------------------------------------------------");
        $display("                          FAIL                             ");
        $display("      out_valid should not overlap with in_valid           ");
        $display("      PATTERN NO.%5d                                       ", pattern_count+1);
        $display("-----------------------------------------------------------");
        #(CYCLE); $finish;
    end
end

//================================================================
// tasks
//================================================================
task reset_task; begin
    force clk  = 1'b0;
    rst_n      = 1'b1;
    in_valid   = 1'b0;
    in_data    = 8'dx;

    $srandom(seed);

    #(CYCLE);
    #(CYCLE); rst_n = 1'b0;
    #(CYCLE); rst_n = 1'b1;

    repeat(2) #(CYCLE);

    if (out_valid !== 1'b0 || out_data !== 1'b0) begin
        fail_task;
        $display("--------------------------------------------------");
        $display("                       FAIL                       ");
        $display("   output signals should be 0 after reset         ");
        $display("--------------------------------------------------");
        #(CYCLE); $finish;
    end

    #(CYCLE); release clk;
    repeat(2) @(negedge clk);
end endtask


task generate_image_task; begin
    for (r = 0; r < IMAGE_SIZE; r = r + 1) begin
        for (c = 0; c < IMAGE_SIZE; c = c + 1) begin
            if ((r%2 == 0) || (c%2 == 0))   image[r][c] = $urandom_range(0, 64);
            else                            image[r][c] = $urandom_range(0, 255);
        end
    end
end endtask


task compute_golden_task; begin
    for (r = 0; r < OUTPUT_SIZE; r = r + 1) begin
        for (c = 0; c < OUTPUT_SIZE; c = c + 1) begin
            p00 = image[r  ][c  ]; p01 = image[r  ][c+1]; p02 = image[r  ][c+2];
            p10 = image[r+1][c  ]; p11 = image[r+1][c+1]; p12 = image[r+1][c+2];
            p20 = image[r+2][c  ]; p21 = image[r+2][c+1]; p22 = image[r+2][c+2];

            // Gx = [-1 0 +1; -2 0 +2; -1 0 +1]
            Gx = -p00 + p02 -2*p10 + 2*p12 -p20 + p22;
            // Gy = [-1 -2 -1; 0 0 0; +1 +2 +1]
            Gy = -p00 - 2*p01 - p02 + p20 + 2*p21 + p22;

            if (Gx < 0) Gx = -Gx;
            if (Gy < 0) Gy = -Gy;
            mag = Gx + Gy;

            golden[r][c] = (mag > THRESHOLD) ? 1'b1 : 1'b0;
        end
    end
end endtask


task flatten_golden_task; begin
    for (r = 0; r < OUTPUT_SIZE; r = r + 1)
        for (c = 0; c < OUTPUT_SIZE; c = c + 1)
            golden_flat[r * OUTPUT_SIZE + c] = golden[r][c];
end endtask


task dump_debug_task; 
begin
    fp = $fopen("hw2_debug.txt", "w");
    if (fp == 0) begin $display("Error: Cannot open hw2_debug.txt"); $finish; end

    $fdisplay(fp, "========================================");
    $fdisplay(fp, " PATTERN NO. %0d", pattern_count + 1);
    $fdisplay(fp, "========================================");
    
    $fdisplay(fp, "\n[ Input Image ]\n");
    for (r = 0; r < IMAGE_SIZE; r = r + 1) begin
        for (c = 0; c < IMAGE_SIZE; c = c + 1) begin
            $fwrite(fp, "%4d ", image[r][c]); // %4d 讓 0~255 的數字對齊
        end
        $fwrite(fp, "\n");
    end

    // 印出 Golden Output (6x6)
    $fdisplay(fp, "\n[ Golden Output ]\n");
    for (r = 0; r < OUTPUT_SIZE; r = r + 1) begin
        for (c = 0; c < OUTPUT_SIZE; c = c + 1) begin
            $fwrite(fp, "%2d ", golden[r][c]); // %2b 印出 0 或 1
        end
        $fwrite(fp, "\n");
    end

    $fclose(fp);
end 
endtask


task pattern_input_task; begin
    repeat($urandom_range(2, 4)) begin
        if (out_valid !== 1'b0) begin
            fail_task;
            $display("--------------------------------------------------");
            $display("                       FAIL                       ");
            $display("  out_valid should be low before input starts     ");
            $display("--------------------------------------------------");
            #(CYCLE); $finish;
        end
        @(negedge clk);
    end

    for (r = 0; r < IMAGE_SIZE; r = r + 1) begin
        for (c = 0; c < IMAGE_SIZE; c = c + 1) begin

            // stall with given chance
            rand_val = $urandom_range(1, 100);
            if (rand_val <= STALL_PROB) begin
                in_valid = 1'b0;
                in_data  = 8'dx;
                repeat(STALL_CYCLE) @(negedge clk);
            end

            // send valid pixel
            in_valid = 1'b1;
            in_data  = image[r][c];
            @(negedge clk);
        end
    end

    in_valid = 1'b0;
    in_data  = 8'dx;
    input_done = 1;
end endtask


task check_ans_task;
    integer out_row, out_col;
    integer last_in_valid_cycle;
    integer last_out_valid_cycle;
begin
    out_bit_count        = 0;
    idle_count           = 0;
    pattern_latency      = 0;
    last_in_valid_cycle  = 0;
    last_out_valid_cycle = 0;
    current_cycle        = 0;
    received_in_count    = 0; 

    while (out_bit_count < NUM_OUTPUT) begin
        @(negedge clk);
        current_cycle = current_cycle + 1;

        // Track the last cycle in_valid was high
        if (in_valid === 1'b1) begin
            last_in_valid_cycle = current_cycle;
            received_in_count = received_in_count + 1;
        end 

        if (out_valid === 1'b1) begin
            idle_count           = 0;
            last_out_valid_cycle = current_cycle;

            out_row = out_bit_count / OUTPUT_SIZE;
            out_col = out_bit_count % OUTPUT_SIZE;

            if (out_data !== golden_flat[out_bit_count]) begin
                fail_task;
                $display("-----------------------------------------------------------");
                $display("                          FAIL                             ");
                $display("                   wrong output value                      ");
                $display("-----------------------------------------------------------");
                $display("  PATTERN NO.%5d  output bit %0d  [row=%0d][col=%0d]       ", pattern_count+1, out_bit_count, out_row, out_col);
                $display("  golden = %0b   out_data = %0b                            ", golden_flat[out_bit_count], out_data);
                $display("-----------------------------------------------------------");
                #(CYCLE); $finish;
            end

            out_bit_count = out_bit_count + 1;

        end 
        else begin
            if (received_in_count == NUM_PIXELS && in_valid === 1'b0) begin
                idle_count = idle_count + 1;

                if (idle_count > OUTPUT_IDLE_TIMEOUT) begin
                    fail_task;
                    $display("-------------------------------------------------------------");
                    $display("                          FAIL                               ");
                    $display("  Output stalled: no out_valid for %0d cycles after input    ", OUTPUT_IDLE_TIMEOUT);
                    $display("  Received %0d / %0d output bits                             ", out_bit_count, NUM_OUTPUT);
                    $display("  PATTERN NO.%5d                                             ", pattern_count+1);
                    $display("-------------------------------------------------------------");
                    #(CYCLE); $finish;
                end
            end
        end
    end

    pattern_latency = last_out_valid_cycle - last_in_valid_cycle;
    total_latency   = total_latency + pattern_latency;

    // ---- All 36 bits received ----
    @(negedge clk);

    if ((out_valid !== 1'b0) || (out_data !== 1'b0)) begin
        fail_task;
        $display("--------------------------------------------------");
        $display("                       FAIL                       ");
        $display("  output did not return to 0 after all output sent");
        $display("  PATTERN NO.%5d                                  ", pattern_count+1);
        $display("--------------------------------------------------");
        #(CYCLE); $finish;
    end

    $display ("\033[1;37m========== \033[1;32mPASS\033[1;37m \033[1;34mPATTERN NO.%5d\033[1;37m | latency cycle = %3d ==========\033[0m", 
              pattern_count+1, pattern_latency);
end endtask


